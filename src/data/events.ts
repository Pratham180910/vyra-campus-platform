export function getEventById(id: string): EventItem | undefined {
  if (!id) return undefined;
  return MOCK_EVENTS.find((e) => e.id.toLowerCase() === id.toLowerCase());
}

export function getRelatedEvents(currentId: string, limit = 3): EventItem[] {
  const current = getEventById(currentId);
  if (!current) return MOCK_EVENTS.slice(0, limit);

  // Filter out the current event
  const others = MOCK_EVENTS.filter((e) => e.id.toLowerCase() !== currentId.toLowerCase());

  // Prioritize same category or shared tags
  const matched = others.filter((e) => {
    const sameCat = e.category === current.category;
    const sharedTag = e.tags && current.tags && e.tags.some((t) => current.tags?.includes(t));
    return sameCat || sharedTag;
  });

  if (matched.length >= limit) {
    return matched.slice(0, limit);
  }

  // Fill remaining slots from others
  const remaining = others.filter((e) => !matched.includes(e));
  return [...matched, ...remaining].slice(0, limit);
}

